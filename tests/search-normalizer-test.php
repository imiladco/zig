<?php
/**
 * نرمال‌سازِ سرچ.
 *
 * این تست‌ها یک قرارداد را نگه می‌دارند: ورودیِ کاربر — با هر کیبورد و
 * هر رسم‌الخطی که تایپ شده — باید به همان چیزی برسد که ادمین در عنوانِ
 * محصول نوشته. اگر «ي» عربی نرمال نشود، یا «۳بعدی» به «3 بعدی» وصل
 * نشود، نتیجه این نیست که سرچ کندتر می‌شود — نتیجه این است که کاربر
 * جستجو می‌کند، هیچ نتیجه‌ای نمی‌بیند، و می‌رود.
 */

require_once __DIR__ . '/bootstrap.php';

require_once dirname(__DIR__) . '/includes/search-normalizer.php';

use Zig3d_Widgets\Search_Normalizer as N;

/* ==========================================================================
 * یکدست‌سازیِ نویسه‌ای — Tier 1
 * ======================================================================= */

Tests::group('نرمالایز › یکدست‌سازیِ نویسه‌ای');

Tests::same('عربی «ي» به فارسی «ی»', N::normalize('ماشين'), 'ماشین');
Tests::same('عربی «ك» به فارسی «ک»', N::normalize('كوچك'), 'کوچک');
Tests::same('رقمِ فارسی به لاتین', N::normalize('۱۲۳'), '123');
Tests::same('رقمِ عربی (اندیک) به لاتین', N::normalize('١٢٣'), '123');

/*
 * اعراب/تشدید در تایپِ روزمره تصادفی حاضر/غایب‌اند — همان کلمه با و
 * بدونِ آن‌ها باید یک نتیجه بدهد، وگرنه نیمی از کاربران بی‌دلیل صفر
 * نتیجه می‌گیرند.
 */
Tests::same('اعراب حذف می‌شود', N::normalize('مَاشِین'), 'ماشین');

Tests::same('فاصله‌هایِ تکراری یکی می‌شوند', N::normalize('سه   بعدی'), 'سه بعدی');
Tests::same('فاصله‌هایِ ابتدا/انتها حذف می‌شوند', N::normalize('  فرز  '), 'فرز');

/*
 * ساختارِ فاصله‌گذاری (ZWNJ در برابرِ فاصلهٔ معمولی) عمداً دست‌نخورده
 * می‌ماند — آن تفاوت مالِ Tier 2 است، نه Tier 1.
 */
Tests::same('ZWNJ در Tier 1 دست‌نخورده می‌ماند', N::normalize("سه\xE2\x80\x8Cبعدی"), "سه\xE2\x80\x8Cبعدی");

/* ==========================================================================
 * Tier 2 — نحوهٔ پیوستنِ کلمات
 * ======================================================================= */

Tests::group('نرمالایز › وریانتِ پیوستن (Tier 2)');

$zwnj = "\xE2\x80\x8C";

/*
 * از هرکدام از «فاصله» و «ZWNJ» شروع کنی، باید به آن‌یکی هم برسی — چون
 * نمی‌دانیم عنوانِ محصول با کدام نوشته شده.
 */
Tests::keeps('«سه بعدی» → شکلِ چسبیده', implode('|', N::joining_variants(N::normalize('سه بعدی'))), 'سهبعدی');
Tests::keeps('«سه بعدی» → شکلِ ZWNJ‌دار', implode('|', N::joining_variants(N::normalize('سه بعدی'))), 'سه' . $zwnj . 'بعدی');

Tests::keeps('«سه' . $zwnj . 'بعدی» → شکلِ فاصله‌دار', implode('|', N::joining_variants(N::normalize('سه' . $zwnj . 'بعدی'))), 'سه بعدی');
Tests::keeps('«سه' . $zwnj . 'بعدی» → شکلِ چسبیده', implode('|', N::joining_variants(N::normalize('سه' . $zwnj . 'بعدی'))), 'سهبعدی');

/*
 * خودِ ورودی نباید دوباره در فهرستِ وریانت‌ها تکرار شود — این کار
 * ‎variants()‎ ی است که تکِ Tier 1 را اضافه می‌کند.
 */
Tests::ok('وریانت‌ها شاملِ خودِ نرمالایزشده نیستند', !in_array('سه بعدی', N::joining_variants(N::normalize('سه بعدی')), true));

/*
 * «سهبعدی» (چسبیده، بدونِ هیچ نشانه‌ای) عمداً پوشش داده نمی‌شود: بدونِ
 * فاصله یا ZWNJ هیچ مرزِ کلمه‌ای معلوم نیست تا از آن جداسازی بسازیم —
 * این محدودیت مالِ همین Tier است، نه یک باگ؛ «سهبعدی» فقط از مسیرِ
 * Tier 3 (وریانتِ عددی) قابلِ رسیدن است، مثلِ «3بعدی».
 */
Tests::same('ورودیِ کاملاً چسبیده چیزی برنمی‌گرداند', N::joining_variants(N::normalize('سهبعدی')), []);
Tests::same('یک‌کلمه‌ایِ بدونِ فاصله/ZWNJ چیزی برنمی‌گرداند', N::joining_variants('فرز'), []);

/* ==========================================================================
 * Tier 3 — رقم↔حرف
 * ======================================================================= */

Tests::group('نرمالایز › وریانتِ عددی (Tier 3)');

foreach (['3 بعدی', '3بعدی'] as $input) {
    $variants = N::numeric_variants(N::normalize($input));
    Tests::keeps('«' . $input . '» به حرف تبدیل می‌شود', implode('|', $variants), 'سه بعدی');
}

Tests::keeps('«سه بعدی» به رقم تبدیل می‌شود', implode('|', N::numeric_variants(N::normalize('سه بعدی'))), '3 بعدی');
Tests::keeps('«3D» به «سه بعدی» تبدیل می‌شود', implode('|', N::numeric_variants(N::normalize('3D'))), 'سه بعدی');
Tests::keeps('«3d» با حرفِ کوچک هم', implode('|', N::numeric_variants(N::normalize('3d'))), 'سه بعدی');

Tests::keeps('«چهار محوره» به «4 محوره» تبدیل می‌شود', implode('|', N::numeric_variants(N::normalize('چهار محوره'))), '4 محوره');

/*
 * این تنها تضمینی است که واقعاً جلوی false-positive را می‌گیرد: بدونِ
 * پسوندِ شناخته‌شده، هیچ رقمی — حتیٔ داخلِ یک قیمت — نباید دستکاری شود.
 * پس ‎numeric_variants‎ برایِ چنین ورودی‌ای باید خالی برگردد (چون تنها
 * چیزی که ‎unique_non_empty‎ فیلتر می‌کند خودِ ورودیِ دست‌نخورده است).
 */
Tests::same('قیمتِ بدونِ پسوند هیچ وریانتی نمی‌سازد', N::numeric_variants(N::normalize('120000 تومان')), []);

/* ==========================================================================
 * Tier 4 — مترادفِ دستی
 * ======================================================================= */

Tests::group('نرمالایز › مترادف (Tier 4)');

$pairs = [['میلینگ', 'فرز']];

Tests::keeps('طرفِ اول → طرفِ دوم', implode('|', N::synonym_variants(N::normalize('میلینگ ماشین'), $pairs)), 'فرز ماشین');
Tests::keeps('طرفِ دوم → طرفِ اول (دوطرفه)', implode('|', N::synonym_variants(N::normalize('فرز CNC'), $pairs)), 'میلینگ');

Tests::same('بدونِ تطبیق، چیزی برنمی‌گردد', N::synonym_variants(N::normalize('روتر'), $pairs), []);
Tests::same('جفتِ ناقص نادیده گرفته می‌شود', N::synonym_variants(N::normalize('میلینگ'), [['میلینگ', '']]), []);

/* ==========================================================================
 * variants() — ترکیبِ هر چهار Tier
 * ======================================================================= */

Tests::group('نرمالایز › variants (ارکستراسیون)');

$v = N::variants('3بعدی');

Tests::ok('همیشه Tier 1 (خودِ نرمالایزشده) حاضر است', $v[0]['tier'] === 1 && $v[0]['text'] === N::normalize('3بعدی'));
Tests::ok('شکلِ حرفیِ عدد هم در خروجی هست', in_array('سه بعدی', array_column($v, 'text'), true));

$tier_of_word = null;
foreach ($v as $entry) {
    if ('سه بعدی' === $entry['text']) {
        $tier_of_word = $entry['tier'];
    }
}
Tests::same('و با Tier درستش (3) برچسب خورده', $tier_of_word, 3);

$v_syn = N::variants('میلینگ ماشین', [['میلینگ', 'فرز']]);
Tests::ok('مترادف هم در ارکستراسیونِ کامل ظاهر می‌شود', in_array('فرز ماشین', array_column($v_syn, 'text'), true));

Tests::same('ورودیِ خالی چیزی برنمی‌گرداند', N::variants('   '), []);

/*
 * بدونِ سقف، یک کلمهٔ چندپهلو می‌توانست دهها وریانت بسازد و WHERE را با
 * دهها LIKE منفجر کند — دقیقاً همان‌جایی که کوئری کند می‌شود.
 */
Tests::ok('تعداد وریانت‌ها هیچ‌وقت از سقف بیشتر نمی‌شود', count(N::variants('3بعدی', [['بعدی', 'محوره']])) <= N::MAX_VARIANTS);

/*
 * تکراری‌ها (بدونِ توجه به بزرگی/کوچکیِ حروفِ لاتین، مثلِ «3D» و «3d»)
 * نباید دوبار در فهرست باشند — هر ردیفِ تکراری یک شرطِ اضافه در SQL
 * است بدونِ هیچ نتیجهٔ جدید.
 */
$texts = array_column(N::variants('3D'), 'text');
$lowered = array_map('mb_strtolower', $texts);
Tests::same('هیچ دو ردیفِ هم‌معنایی هم‌زمان در خروجی نیست', count($lowered), count(array_unique($lowered)));

/* ==========================================================================
 * جفتِ SQLیِ نرمال‌ساز
 *
 * ‎normalize()‎ و ‎sql_expr()‎ باید *همان* نگاشت را اعمال کنند. اگر یکی
 * عوض شود و دیگری نه، دو طرفِ مقایسه از هم واگرا می‌شوند و سرچ بی‌صدا
 * نتیجه گم می‌کند — بدونِ هیچ خطایی.
 * ======================================================================= */

Tests::group('نرمالایز › عبارتِ SQL');

$expr = N::sql_expr('wp_posts.post_title');

Tests::keeps('نامِ ستون دست‌نخورده در مرکزِ عبارت است', $expr, 'wp_posts.post_title');
Tests::keeps('یِ عربی نگاشت می‌شود', $expr, "'ي', 'ی'");
Tests::keeps('کافِ عربی هم', $expr, "'ك', 'ک'");
Tests::keeps('تای گردِ عربی هم', $expr, "'ة', 'ه'");
Tests::keeps('رقمِ فارسی هم', $expr, "'۵', '5'");
Tests::keeps('رقمِ عربیِ اندیک هم', $expr, "'٥', '5'");

/*
 * تعدادِ ‎REPLACE‎ باید دقیقاً به‌اندازهٔ نگاشت باشد — نه کمتر (یعنی
 * نویسه‌ای جا افتاده) و نه بیشتر (یعنی چیزی دوبار اعمال شده).
 */
$map = (new ReflectionClass(N::class))->getConstant('CHAR_MAP');
Tests::same('به‌ازایِ هر نویسهٔ نگاشت یک REPLACE ساخته می‌شود', substr_count($expr, 'REPLACE('), count($map));

/*
 * و مهم‌ترین سنجه: هر نویسه‌ای که ‎normalize()‎ عوض می‌کند، باید در
 * عبارتِ SQL هم عوض شود.
 */
$missing = [];

foreach ($map as $from => $to) {
    if (false === strpos($expr, "'" . $from . "', '" . $to . "'")) {
        $missing[] = $from;
    }
}

Tests::same('هیچ نویسه‌ای بینِ PHP و SQL جا نمی‌افتد', $missing, []);
