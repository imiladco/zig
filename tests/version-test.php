<?php
/**
 * همگامیِ نسخه.
 *
 * این سنجه دقیقاً همان چیزی است که نبودنش یک باگِ واقعی ساخت: چهار
 * کامیت پشتِ سرِ هم CSS و کنترلِ تازه به گالری اضافه کردند بدونِ اینکه
 * ‎ZIG3D_WIDGETS_VERSION‎ یک‌بار هم عوض شود. نتیجه‌اش این بود که
 * ‎maybe_flush_after_update()‎ هیچ‌وقت اجرا نشد — نه کشِ CSSِ خودِ
 * المنتور باطل شد، نه رشتهٔ ‎?ver=‎ فایلِ استایل عوض شد — و «بعضی
 * استایل‌ها از پنل اعمال نمی‌شوند» دقیقاً همین است: کنترل در پنل هست،
 * مقدار ذخیره می‌شود، ولی CSSِ کامپایل‌شده‌ای که واقعاً سرو می‌شود
 * مالِ قبل از آن کنترل است.
 *
 * راهِ گرفتنش این نیست که «نسخه را زیاد کن» چون آن هم فراموش می‌شود؛
 * راهش این است که هر بار کسی یادش رفت، تست قرمز شود.
 */

require_once __DIR__ . '/bootstrap.php';

$root = dirname(__DIR__);

Tests::group('نسخه');

$main = (string) file_get_contents($root . '/zig3d-elementor-widgets.php');

preg_match('/^\s*\*\s*Version:\s*([0-9.]+)/m', $main, $header);
preg_match("/define\\('ZIG3D_WIDGETS_VERSION',\\s*'([0-9.]+)'\\)/", $main, $constant);

Tests::ok('نسخه در کامنتِ بالای فایل پیدا شد', !empty($header[1]), 'یافت نشد');
Tests::ok('نسخه در ثابتِ PHP پیدا شد', !empty($constant[1]), 'یافت نشد');

Tests::same(
    'کامنتِ پلاگین و ثابتِ PHP یک نسخه را می‌گویند',
    $header[1] ?? null,
    $constant[1] ?? null
);
