<?php
/**
 * فهرستِ اسلایدهای گالری.
 *
 * تمام ارزشِ این فایل در یک جمله است: گالریِ قالبِ قبلی دو فهرست داشت و
 * هیچ‌کدام از خطاهایش در خروجی HTML دیده نمی‌شد. صفحه درست بود، تصویرها
 * درست بودند، فقط بندانگشتیِ اول چیز دیگری باز می‌کرد و تصویر شاخص هیچ
 * راهی برای برگشتن نداشت.
 *
 * پس چیزی که اینجا سنجیده می‌شود «آیا رندر شد» نیست — «آیا هر سه بخشِ
 * رابط از یک فهرستِ واحد می‌خوانند و آن فهرست درست است» است.
 */

require_once __DIR__ . '/bootstrap.php';
require_once __DIR__ . '/lib/elementor-stub.php';
require_once __DIR__ . '/lib/woocommerce-stub.php';

$root = dirname(__DIR__);

require_once $root . '/includes/price.php';
require_once $root . '/includes/gallery.php';

use Zig3d_Widgets\Gallery;

/* ==========================================================================
 * ترتیب
 * ======================================================================= */

Tests::group('گالری › ترتیب');

Tests::same(
    'شاخص اول می‌آید، بعد گالری',
    Gallery::order(10, [20, 30]),
    [10, 20, 30]
);

Tests::same(
    'بدون شاخص، گالری تنها می‌ماند',
    Gallery::order(0, [20, 30]),
    [20, 30]
);

Tests::same(
    'بدون گالری، شاخص یک اسلاید کامل است',
    Gallery::order(10, []),
    [10]
);

Tests::same(
    'هیچ تصویری نباشد، فهرست خالی است',
    Gallery::order(0, []),
    []
);

/*
 * این همان حالتی است که ناهماهنگی را می‌ساخت. مدیرِ فروشگاه معمولاً تصویر
 * شاخص را در گالری هم می‌گذارد تا در بندانگشتی‌ها دیده شود — و بدون
 * یکتاسازی، همان تصویر دو اسلاید و دو بندانگشتی می‌شد و شمارنده یکی بیشتر
 * می‌شمرد.
 */
Tests::same(
    'شاخصی که در گالری هم هست، یک بار می‌آید',
    Gallery::order(20, [10, 20, 30]),
    [20, 10, 30]
);

Tests::same(
    'تکرار در خودِ گالری هم یکی می‌شود',
    Gallery::order(0, [10, 10, 20, 10]),
    [10, 20]
);

/*
 * ترتیبِ اولین ظهور باید حفظ شود: شاخص جای اولش را از دست نمی‌دهد، حتی
 * وقتی وسطِ گالری هم آمده. اگر ‎array_unique‎ روزی با چیزی جایگزین شود که
 * ترتیب را به هم بزند، اسلاید اول عوض می‌شود و هیچ خطایی در کار نیست.
 */
Tests::same(
    'یکتاسازی ترتیب را به هم نمی‌زند',
    Gallery::order(30, [10, 20, 30, 40]),
    [30, 10, 20, 40]
);

/* ==========================================================================
 * ورودیِ کثیف
 * ======================================================================= */

Tests::group('گالری › ورودی نامعتبر');

/*
 * ‎get_gallery_image_ids()‎ در عمل رشته برمی‌گرداند نه عدد، و پیوستی که
 * حذف شده باشد می‌تواند ‎0‎ یا ‎''‎ بگذارد. هر کدام از این‌ها یک فریمِ خالی
 * می‌ساخت که در صفحه فقط یک کادر خاکستری بود.
 */
Tests::same(
    'رشته‌های عددی به عدد تبدیل می‌شوند',
    Gallery::order(0, ['10', '20']),
    [10, 20]
);

Tests::same(
    'صفر و رشتهٔ خالی حذف می‌شوند',
    Gallery::order(0, [10, 0, '', 20, null]),
    [10, 20]
);

Tests::same(
    'شناسهٔ منفی هم اسلاید نیست',
    Gallery::order(0, [-5, 10]),
    [10]
);

/* ==========================================================================
 * سقف و خاموش‌کردن شاخص
 * ======================================================================= */

Tests::group('گالری › سقف');

Tests::same(
    'سقف صفر یعنی بی‌سقف',
    Gallery::order(10, [20, 30, 40], true, 0),
    [10, 20, 30, 40]
);

Tests::same(
    'سقف کوچک‌تر از تعداد، از ابتدا می‌برد',
    Gallery::order(10, [20, 30, 40], true, 2),
    [10, 20]
);

Tests::same(
    'سقف بزرگ‌تر از تعداد، بی‌اثر است',
    Gallery::order(10, [20], true, 9),
    [10, 20]
);

/*
 * سقف بعد از یکتاسازی اعمال می‌شود، نه قبلش. اگر برعکس بود، مدیری که سقف
 * را روی ۳ گذاشته و شاخصش در گالری تکرار شده، دو تصویر می‌دید نه سه.
 */
Tests::same(
    'سقف بعد از حذف تکراری‌ها شمرده می‌شود',
    Gallery::order(20, [20, 30, 40], true, 3),
    [20, 30, 40]
);

Tests::same(
    'شاخصِ خاموش، از فهرست بیرون می‌ماند',
    Gallery::order(10, [20, 30], false),
    [20, 30]
);

/*
 * و وقتی شاخص خاموش است ولی در گالری هم هست، باید بماند: تصمیمِ «شاخص
 * اسلاید نباشد» دربارهٔ *جایگاهِ* شاخص است، نه دربارهٔ تصویری که مدیر
 * عمداً در گالری گذاشته.
 */
Tests::same(
    'ولی اگر در گالری باشد، حذف نمی‌شود',
    Gallery::order(20, [10, 20], false),
    [10, 20]
);

/* ==========================================================================
 * برچسب شماره
 * ======================================================================= */

Tests::group('گالری › شماره');

Tests::same('شماره از یک شروع می‌شود', Gallery::label(0, false), '1');
Tests::same('و نه از صفر', Gallery::label(3, false), '4');
Tests::same('ارقام فارسی', Gallery::label(0, true), '۱');
Tests::same('عدد دورقمی فارسی', Gallery::label(11, true), '۱۲');

/* ==========================================================================
 * دادهٔ کامل › ‎slides‎ در برابرِ ‎all_slides‎
 * ======================================================================= */

Tests::group('گالری › دادهٔ کامل');

/*
 * دلیلِ وجودِ دو فهرست: ‎max‎ فقط باید *نمایشِ* صحنه و نوارِ اصلی را
 * محدود کند، نه دسترسیِ مشتری به بقیهٔ عکس‌ها. اگر ‎all_slides‎ هم بریده
 * می‌شد، لایت‌باکس دقیقاً همان محدودیت را تکرار می‌کرد و «چند عکسِ
 * دیگر» اصلاً قابلِ دیدن نمی‌ماند.
 */
$product = new WC_Product(['id' => 50, 'image' => 1, 'gallery' => [2, 3, 4, 5, 6]]);
$data    = Gallery::data($product, ['max' => 3]);

Tests::same('فهرستِ نمایشی با سقف بریده می‌شود', $data['slides'], [1, 2, 3]);
Tests::same('فهرستِ کامل بریده نمی‌شود', $data['all_slides'], [1, 2, 3, 4, 5, 6]);

$unbounded = Gallery::data($product, ['max' => 0]);

Tests::same(
    'بدونِ سقف، هر دو فهرست یکی‌اند',
    $unbounded['slides'],
    $unbounded['all_slides']
);

/*
 * تکراری‌ها هم باید در هر دو فهرست یک‌جور یکتا شوند — وگرنه شمارشِ
 * «چندتای پنهان» (تفاوتِ طولِ این دو فهرست) غلط از آب درمی‌آمد.
 */
$dup_product = new WC_Product(['id' => 51, 'image' => 10, 'gallery' => [10, 11, 12]]);
$dup_data    = Gallery::data($dup_product, ['max' => 2]);

Tests::same('فهرستِ نمایشی، تکراری را یکتا کرده', $dup_data['slides'], [10, 11]);
Tests::same('فهرستِ کامل هم همین‌طور', $dup_data['all_slides'], [10, 11, 12]);
