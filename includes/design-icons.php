/**
 * آیکون‌هایِ خودِ طرح، همان‌طور که از فیگما بیرون آمده‌اند.
 *
 * چرا این کلاس وجود دارد — و چرا آیکونِ کتابخانه جایش را نمی‌گیرد:
 *
 * پیش از این، پیش‌فرضِ هر آیکونِ ویجتِ سرچ یک گلیفِ Font Awesome بود که
 * «شبیه» آیکونِ طرح بود، نه خودش. تفاوت‌ها هم تزئینی نبودند: چیپِ
 * «جستجوهایِ پرطرفدار» در طرح یک نمودارِ صعودی است، ولی
 * ‎fa-arrow-up-right-from-square‎ یک فلشِ مورب با کادر است — دو معنیِ
 * متفاوت. ضربدرِ فیلد در طرح دو میلهٔ ۲ پیکسلیِ گِردشده است، نه ضربدرِ
 * تیزِ ‎fa-times‎. ذره‌بین هم در طرح Iconly است با ضخامت و نسبتِ خودش.
 *
 * پس فایل‌هایِ ‎assets/icons/*.svg‎ صادرشدهٔ همان نودهایِ فیگما هستند و
 * این کلاس درونشان می‌خواند. سه نکتهٔ پیاده‌سازی:
 *
 *   • رنگ‌ها در فایل به ‎currentColor‎ بدل شده‌اند، پس هر آیکون از
 *     ‎color‎ی که CSS یا تبِ استایلِ المنتور می‌دهد رنگ می‌گیرد. اگر
 *     رنگِ فیگما توی خودِ ‎path‎ می‌ماند، کنترلِ رنگ بی‌اثر می‌شد.
 *   • دو آیکونی که در فیگما از چند نودِ جدا ساخته شده‌اند (ذره‌بین و
 *     ضربدر) اینجا در یک ‎viewBox‎ی هم‌اندازهٔ نودِ اصلی سرِ جای خودشان
 *     نشسته‌اند؛ ‎transform‎هایِ چرخش هم همان‌هایی‌اند که فیگما داشت،
 *     نه تقریبِ دستی.
 *   • خواندنِ فایل از ‎Svg::sanitize()‎ نمی‌گذرد: این فایل‌ها بخشی از
 *     خودِ افزونه‌اند، نه آپلودِ کاربر. پاک‌سازی یعنی یک پارسِ DOM به
 *     ازای هر آیکون در هر درخواست، بابتِ ورودی‌ای که تهدید نیست.
 */
final class Design_Icons {

    /** @var array<string,string> حافظهٔ درون‌درخواستی؛ هر آیکون چند بار در صفحه تکرار می‌شود */
    private static array $memo = [];

    /**
     * SVGی درون‌خطیِ یک آیکونِ طرح. رشتهٔ خالی یعنی چنین آیکونی نداریم —
     * که برایِ چیپِ «جستجوهایِ اخیر» حالتِ درست است: در طرح آیکون ندارد.
     */
    public static function get(string $name): string {
        if (isset(self::$memo[$name])) {
            return self::$memo[$name];
        }

        // نامِ آیکون از تنظیماتِ ویجت می‌آید نه از درخواست، ولی این شرط
        // هزینه‌ای ندارد و مسیر را در هر حالت داخلِ همین پوشه نگه می‌دارد.
        if (!preg_match('/^[a-z0-9-]+$/', $name)) {
            return self::$memo[$name] = '';
        }

        $path = dirname(__DIR__) . '/assets/icons/' . $name . '.svg';

        if (!is_file($path)) {
            return self::$memo[$name] = '';
        }

        $contents = file_get_contents($path);

        return self::$memo[$name] = false === $contents ? '' : trim($contents);
    }
}
