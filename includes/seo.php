/**
 * تصمیم‌های سئو برای حالت‌های فیلترشدهٔ آرشیو.
 *
 * مسئله‌ای که این کلاس حل می‌کند، مسئلهٔ ناوبری وجهی است: با پنج گروه فیلتر
 * و ده گزینه در هرکدام، تعداد آدرس‌های ممکن از تعداد محصولات فروشگاه
 * بیشتر می‌شود. هیچ‌کدام هم خطا نمی‌دهند — فقط خزندهٔ موتور جستجو وقتش را
 * صرف ترکیب‌هایی می‌کند که هیچ‌کس دنبالشان نیست، و صفحه‌های واقعی دیرتر
 * ایندکس می‌شوند.
 *
 * سه ابزار داریم و هر سه لازم‌اند:
 *
 *   • ‎noindex‎ روی حالت‌های فیلترشده — می‌گوید «این را ایندکس نکن».
 *   • ‎canonical‎ به سمت آدرس پایه — می‌گوید «اصلش آنجاست».
 *   • ‎follow‎ که همیشه روشن می‌ماند — چون لینک‌های داخل همان صفحه (خودِ
 *     محصولات) باید کشف شوند. ‎nofollow‎ اینجا یعنی محصولاتی که فقط از
 *     مسیر فیلتر پیدا می‌شوند، هیچ‌وقت پیدا نشوند.
 *
 * ترتیب و صفحه فرق دارند و عمداً ایندکس‌پذیر می‌مانند: تعدادشان محدود است
 * (چند گزینهٔ ترتیب، چند صفحه) و صفحهٔ دوم یک دسته، محتوای واقعیِ متفاوتی
 * دارد که باید پیدا شود.
 */
final class Seo {

    /** همه‌چیز ایندکس شود — حتی ترکیب فیلترها */
    public const INDEX_ALL = 'all';

    /**
     * فقط حالت بدون فیلتر ایندکس شود.
     *
     * محافظه‌کارترین حالت و پیش‌فرض. برای فروشگاهی که هنوز روی صفحه‌های
     * فیلترشده کار سئویی نکرده، این همان چیزی است که می‌خواهد.
     */
    public const INDEX_CLEAN = 'clean';

    /**
     * حالت تک‌فیلتری هم ایندکس شود.
     *
     * برای وقتی که «برند X» یا «۵ محور» خودشان عبارت جست‌وجو هستند. ولی
     * فقط *یک* فیلتر: به‌محض دو فیلتر، انفجار ترکیبی شروع می‌شود.
     */
    public const INDEX_SINGLE = 'single';

    /* =====================================================================
     * ایندکس
     * =================================================================== */

    /**
     * آیا این حالت باید ایندکس شود؟
     *
     * صفحه و ترتیب عمداً بررسی نمی‌شوند — آن‌ها تعداد محدودی حالت می‌سازند
     * و صفحهٔ دوم محتوای واقعی دارد. فقط فیلترها انفجار می‌سازند.
     */
    public static function is_indexable(Query_State $state, string $policy = self::INDEX_CLEAN): bool {
        if (self::INDEX_ALL === $policy) {
            return true;
        }

        if (!$state->is_filtered()) {
            return true;
        }

        if (self::INDEX_SINGLE !== $policy) {
            return false;
        }

        /*
         * «تک‌فیلتری» یعنی یک گروه *و* یک گزینه. دو برند انتخاب‌شده هم یک
         * گروه است ولی محتوایش ترکیبی است و همان انفجار را شروع می‌کند.
         */
        return 1 === count($state->filters()) && 1 === $state->count();
    }

    /**
     * محتوای متاتگ ‎robots‎.
     *
     * ‎follow‎ همیشه هست، حتی روی ‎noindex‎: لینک محصولات داخل همین صفحه
     * باید دنبال شوند. جداکردن این دو همان چیزی است که «فیلتر را ایندکس
     * نکن» را از «محصولاتِ پشت فیلتر را گم کن» جدا می‌کند.
     */
    public static function robots(Query_State $state, string $policy = self::INDEX_CLEAN): string {
        return self::is_indexable($state, $policy) ? 'index, follow' : 'noindex, follow';
    }

    /* =====================================================================
     * canonical
     * =================================================================== */

    /**
     * آدرس کانونیکال این حالت.
     *
     * فیلترها می‌افتند، ترتیب و صفحه می‌مانند. دلیلش همان تفکیک بالاست:
     * صفحهٔ دوم محتوای دیگری دارد و کانونیکال‌کردنش به صفحهٔ اول یعنی
     * گفتن «این صفحه تکراری است» دربارهٔ محصولاتی که جای دیگری نیستند —
     * خطای رایجی که کل صفحات عمیق را از ایندکس بیرون می‌اندازد.
     *
     * وقتی حالت ایندکس‌پذیر است، کانونیکال به خودش اشاره می‌کند؛ وگرنه به
     * نسخهٔ بدون فیلتر.
     */
    public static function canonical(
        string $base_url,
        Query_State $state,
        array $operators = [],
        string $policy = self::INDEX_CLEAN
    ): string {
        $target = self::is_indexable($state, $policy) ? $state : $state->cleared()->with_page($state->page());

        $vars = $target->to_query_vars($operators);

        return $vars ? add_query_arg($vars, $base_url) : $base_url;
    }

    /* =====================================================================
     * لینک‌های واقعی
     * =================================================================== */

    /**
     * آدرس یک حالت — برای ‎href‎ لینک‌ها.
     *
     * هر چیزی که کلیک‌شدنی است باید یک ‎<a href>‎ واقعی باشد، حتی وقتی
     * جاوااسکریپت رویش سوار می‌شود. دو دلیل دارد و هیچ‌کدام تزئینی نیست:
     * بدون آن، صفحه بدون JS اصلاً کار نمی‌کند، و خزنده‌ها — از جمله
     * خزنده‌های هوش مصنوعی که JS اجرا نمی‌کنند — هیچ راهی به صفحهٔ دوم و
     * به حالت‌های فیلترشده ندارند.
     */
    public static function url(string $base_url, Query_State $state, array $operators = []): string {
        $vars = $state->to_query_vars($operators);

        return $vars ? add_query_arg($vars, $base_url) : $base_url;
    }

    /* =====================================================================
     * دادهٔ ساختاریافته
     * =================================================================== */

    /**
     * ‎ItemList‎ برای محصولات یک صفحه.
     *
     * چرا همین‌جا و نه یک افزونهٔ سئو: این فهرست باید *دقیقاً* همان چیزی
     * باشد که رندر شده. اگر جای دیگری ساخته شود، دیر یا زود از محتوای
     * دیده‌شده جدا می‌افتد — و دادهٔ ساختاریافته‌ای که با صفحه نمی‌خواند،
     * از نبودش بدتر است.
     *
     * ‎position‎ عمداً از شمارهٔ صفحه حساب می‌شود، نه از یک تا: محصول اول
     * صفحهٔ سوم، دوازدهمین محصول فهرست است نه اولی.
     *
     * @param array<int,array{url:string,name:string}> $items
     */
    public static function item_list(array $items, int $page = 1, int $per_page = 12): array {
        $offset  = ($page - 1) * $per_page;
        $entries = [];

        foreach (array_values($items) as $index => $item) {
            $url  = trim((string) ($item['url'] ?? ''));
            $name = trim((string) ($item['name'] ?? ''));

            if ('' === $url) {
                continue;
            }

            $entry = [
                '@type'    => 'ListItem',
                'position' => $offset + $index + 1,
                'url'      => $url,
            ];

            if ('' !== $name) {
                $entry['name'] = $name;
            }

            $entries[] = $entry;
        }

        return [
            '@context'        => 'https://schema.org',
            '@type'           => 'ItemList',
            'itemListElement' => $entries,
        ];
    }
}
