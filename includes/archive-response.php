/**
 * قرارداد پاسخ آژاکسِ آرشیو.
 *
 * یک تصمیم دارد و همه‌چیزِ این کلاس از همان یکی می‌آید:
 *
 *     «هیچ محصولی با این فیلتر نیست» یک خطای فنی نیست.
 *
 * تایم‌اوت، ‎500‎، نانسِ منقضی و قطعی شبکه خطای فنی‌اند: کاربر کاری نکرده،
 * چیزی خراب شده، و تنها کار معقول «دوباره تلاش کن» است. ولی نتیجهٔ خالی،
 * *پاسخِ درستِ* سیستم به سؤالِ درستِ کاربر است؛ جوابش «فیلتر را بردار»
 * است، نه «دوباره تلاش کن».
 *
 * اگر این دو یک مسیر داشته باشند، کاربری که برند نایاب را انتخاب کرده یک
 * آلرت قرمز با دکمهٔ «تلاش مجدد» می‌بیند و هرچه بزندش، همان آلرت برمی‌گردد.
 *
 * پس قرارداد این است:
 *
 *   • درخواستی که *فهمیده* شد، همیشه ‎200‎ برمی‌گردد — حتی اگر نتیجه‌اش
 *     صفر باشد یا آدرسش بی‌معنا. وضعیت داخل بدنه می‌آید، در ‎state‎.
 *   • درخواستی که فهمیده *نشد* اصلاً پاکت ندارد: کد HTTP غیر ۲xx و تمام.
 *
 * یعنی سمت کلاینت یک شرط بیشتر لازم نیست:
 *
 *     if (!response.ok) → آلرتِ تلاش مجدد، بدون دست‌زدن به گرید
 *     else              → data.state رابط کاربری را می‌چرخاند، بدون آلرت
 *
 * ‎404‎ سئو عمداً اینجا نیست. آن مالِ درخواستِ *سند* است (نوار آدرس،
 * خزنده، بوکمارک) و ‎Archive_Head‎ می‌فرستدش. تکرارش روی یک ‎fetch‎ فقط
 * باعث می‌شود ‎response.ok‎ دروغ بگوید و همان دو مسیر دوباره یکی شوند.
 */
final class Archive_Response {

    /* ---------------------------------------------------------------------
     * خطاهای فنی — تنها چیزهایی که آلرتِ «تلاش مجدد» را نشان می‌دهند
     * ------------------------------------------------------------------ */

    /** نانس منقضی یا جعلی */
    public const FAIL_NONCE = 'nonce';

    /** پارامترهای درخواست شکل درستی ندارند */
    public const FAIL_REQUEST = 'request';

    /** چیزی سمت سرور ترکید */
    public const FAIL_SERVER = 'server';

    /**
     * نسخهٔ قرارداد.
     *
     * در هر پاکت می‌رود و کلاینت می‌سنجدش. مسئله‌ای که حل می‌کند کوتاه ولی
     * واقعی است: بین بارگذاری فایل JS و به‌روزرسانی افزونه، مرورگر ممکن
     * است اسکریپت قدیمی را داشته باشد و سرور پاکت جدید بدهد. بدون این
     * عدد، کلاینت قدیمی کلید ناشناخته را نادیده می‌گیرد و کاربر یک رابط
     * نیمه‌کاره می‌بیند بدون هیچ خطایی.
     *
     * با این عدد، همان حالت به مسیر «خطای فنی» می‌رود: گرید قبلی سر جایش،
     * دکمهٔ تلاش مجدد بالا — و رفرش صفحه خودش درستش می‌کند.
     *
     * فقط وقتی زیاد شود که *شکل* پاکت بشکند. افزودن یک کلید تازه شکستن
     * نیست؛ حذف یا تغییر معنای یکی هست.
     */
    public const CONTRACT = 1;

    /**
     * کد HTTP هر خطا.
     *
     * صریح نوشته می‌شوند چون پیش‌فرضِ ‎wp_send_json_error()‎ هم ‎200‎ است، و
     * یک شکستِ نانس که با ‎200‎ برگردد، دقیقاً همان چیزی است که این کلاس
     * برای جلوگیری‌اش نوشته شده: کلاینت آن را «موفق» می‌خواند و دنبال
     * ‎state‎ می‌گردد که وجود ندارد.
     *
     * ‎403‎ برای نانس، چون واقعاً یک ردِ مجوز است — و مرورگر باید بتواند
     * تشخیصش بدهد تا کلاینت بعد از رفرشِ نانس دوباره امتحان کند.
     */
    public const FAILURES = [
        self::FAIL_NONCE   => 403,
        self::FAIL_REQUEST => 400,
        self::FAIL_SERVER  => 500,
    ];

    public static function failure_status(string $code): int {
        return self::FAILURES[$code] ?? 500;
    }

    /* =====================================================================
     * پاکت
     * =================================================================== */

    /**
     * پاسخ یک درخواستِ فهمیده‌شده.
     *
     * ‎state‎ اولین کلید است و اتفاقی نیست: همان ماشین وضعیتی است که کد
     * HTTP سند و متاتگ ‎robots‎ را هم تعیین می‌کند. یک منبع، سه مصرف —
     * وگرنه روزی می‌رسد که سرور ‎404‎ می‌دهد و گرید با خوش‌رویی محصول نشان
     * می‌دهد.
     *
     * قطعه‌های HTML جدا از هم می‌آیند، نه به‌صورت یک بلوکِ یکپارچه. دلیلش
     * فقط اندازه نیست: بعد از یک کلیکِ فیلتر، سایدبار باید شمارش‌های تازه را
     * بگیرد ولی *فوکوس* باید سر همان چک‌باکس بماند. با یک بلوک، کل سایدبار
     * جایگزین می‌شود و فوکوس می‌پرد به ‎<body>‎.
     *
     * کلیدهای HTML اختیاری‌اند و کلیدِ نبوده یعنی «دست نزن»: یک کلیکِ
     * صفحه‌بندی، سایدبار را عوض نمی‌کند و فرستادنش فقط پهنای باند و یک
     * جایگزینیِ بی‌دلیل DOM است.
     *
     * @param string               $state     یکی از ‎Seo::STATE_*‎
     * @param array{page:int,pages:int,found:int,url:string} $meta
     * @param array<string,string> $fragments قطعه‌های HTML: ‎grid‎، ‎facets‎، ‎pagination‎، ‎count‎، ‎sorts‎
     */
    public static function envelope(string $state, array $meta, array $fragments = []): array {
        $payload = [
            'contract' => self::CONTRACT,
            'state'    => self::state($state),

            /*
             * آدرسی که باید در ‎history‎ بنشیند، از خودِ سرور.
             *
             * کلاینت هم می‌تواند بسازدش، ولی آن‌وقت دو جا قرارداد آدرس را
             * می‌دانند و روزی که ‎query_type_*‎ عوض شود، یکی‌شان یادش
             * می‌رود. آدرسِ ‎history‎ باید دقیقاً همان آدرسی باشد که اگر
             * کاربر رفرش کند، همین صفحه را بدهد.
             */
            'url'      => (string) ($meta['url'] ?? ''),
            'page'     => max(1, (int) ($meta['page'] ?? 1)),
            'pages'    => max(0, (int) ($meta['pages'] ?? 0)),
            'found'    => max(0, (int) ($meta['found'] ?? 0)),
        ];

        foreach (['grid', 'facets', 'pagination', 'count', 'sorts'] as $key) {
            if (isset($fragments[$key])) {
                $payload[$key] = (string) $fragments[$key];
            }
        }

        return $payload;
    }

    /* =====================================================================
     * معنای وضعیت برای رابط کاربری
     * =================================================================== */

    /**
     * آیا کاربر به‌جای محصول، حالتِ «چیزی پیدا نشد» را می‌بیند؟
     *
     * خودِ قطعهٔ ‎grid‎ همیشه درست است — سرور یا کارت‌ها را فرستاده یا بلوکِ
     * خالی را — پس کلاینت برای *جایگزینی* به این تابع نیازی ندارد. این
     * برای کارهای اطرافِ گرید است: متنی که به ‎aria-live‎ اعلام می‌شود، و
     * اینکه اسکرولِ خودکار باید خاموش بماند یا نه.
     *
     * ‎invalid‎ عمداً بیرون است. ‎?filter_ghost=x‎ معمولاً یک لینکِ کهنه است،
     * نه حملهٔ کسی؛ ووکامرس پارامترِ ناشناخته را اعمال نمی‌کند و دسته
     * محتوایش را دارد. صفحه ‎404‎ و ‎noindex‎ می‌گیرد — که تصمیمِ خزنده
     * است — ولی کاربری که آن لینک را باز کرده، به‌جای صفحهٔ خالی، همان
     * دسته را می‌بیند.
     */
    public static function shows_empty(string $state): bool {
        return in_array(
            $state,
            [Seo::STATE_EMPTY, Seo::STATE_FILTERED_EMPTY, Seo::STATE_PAGE_MISSING],
            true
        );
    }

    /** وضعیت‌هایی که پاکت می‌تواند حمل کند */
    public const STATES = [
        Seo::STATE_OK,
        Seo::STATE_EMPTY,
        Seo::STATE_FILTERED_EMPTY,
        Seo::STATE_PAGE_MISSING,
        Seo::STATE_INVALID,
    ];

    /**
     * وضعیتِ معتبر، وگرنه ‎ok‎.
     *
     * فهرست بسته است و نگهبانش همین‌جاست. اگر روزی وضعیت تازه‌ای اضافه شود،
     * کلاینتِ قدیمی آن را نمی‌شناسد و باید یک رفتار پیش‌فرضِ *بی‌ضرر* داشته
     * باشد؛ ‎ok‎ همان است: گرید را نشان بده. جایگزینش این بود که رشتهٔ
     * ناشناخته را عیناً بفرستیم و کلاینت روی یک ‎switch‎ بی‌تطبیق، هیچ‌کدام
     * از حالت‌ها را رندر نکند و کاربر یک ناحیهٔ خالی ببیند.
     */
    public static function state(string $state): string {
        return in_array($state, self::STATES, true) ? $state : Seo::STATE_OK;
    }
}
